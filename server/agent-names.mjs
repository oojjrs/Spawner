export function suggestAgentName(tribe, agents, nextAgentId) {
  const names = AGENT_NAMES[tribe] || AGENT_NAMES.bean;
  const used = new Set(agents.filter(agent => agent.health > 0).map(agent => agent.name));
  const start = (nextAgentId - 1) % names.length;
  for (let round = 0; ; round++) {
    for (let offset = 0; offset < names.length; offset++) {
      const name = names[(start + offset) % names.length] + (round ? " " + (round + 1) : "");
      if (!used.has(name)) return name;
    }
  }
}
