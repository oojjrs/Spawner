const designs = new Map();
const repeat = (gene, count) => Array(count).fill(gene);

function workerGenes(tribe, level) {
  if (level === 1) return STARTING_WORKER_GENES[tribe];
  const genes = ["gather", ...repeat("capacity", level + 1), ...repeat("harvestSpeed", level * 2),
    ...repeat("movement", level), ...repeat("health", level === 4 ? 2 : 1)];
  if (level >= 3) genes.push("lifespan", "lifespan");
  if (level === 4) genes.push("regeneration", "health");
  return genes;
}

function militaryGenes(tribe, level, variant) {
  const genes = ["antenna", "health", "movement", "vision"];
  if (level >= 3) genes.push("lifespan", "lifespan", "movement");
  if (level === 4) genes.push("health", "movement");
  if (variant === 0) genes.push("blade", "power", "power", "speed", "health");
  if (variant === 1) genes.push("blade", "carapace", "carapace", "power", "health");
  if (variant === 2) genes.push("secretion", "rangedPower", "rangedPower", "rangedSpeed", "movement");
  if (variant === 3) genes.push("blade", "secretion", "power", "rangedPower", "carapace");
  if (level >= 3) genes.push(variant === 1 ? "block" : variant === 2 ? "area" : "combo");
  if (level >= 3) {
    if (tribe === "pebble") genes.push("carapace", "health");
    else if (tribe === "spore") genes.push(variant >= 2 ? "rangedPower" : "health", "movement");
    else if (tribe === "spring") genes.push("movement", variant === 2 ? "rangedSpeed" : "speed");
    else genes.push("health", variant === 2 ? "rangedPower" : "power");
  }
  if (level === 4) genes.push(variant === 1 ? "reflection" : variant === 2 ? "penetration" : "lifesteal");
  return genes;
}

export function tribeDesign(tribe, level, variant) {
  if (!TRIBE_INVASION[tribe] || !Number.isInteger(level) || level < 1 || level > 4 ||
      !Number.isInteger(variant) || variant < -1 || variant > 3 || variant >= 0 && level < 2) return null;
  if (variant < 0) return tribeWorkerDesign(level);
  const key = tribe + ":" + level + ":" + variant;
  if (!designs.has(key)) {
    const genes = variant < 0 ? workerGenes(tribe, level) : militaryGenes(tribe, level, variant);
    const placementKey = variant < 0 ? level === 1 ? tribe + ":1" : "worker:" + level :
      level === 2 ? "military:2:" + variant : key;
    const layout = placements[placementKey];
    const pieces = genes.map((gene, index) => ({ gene, grade: ATTRIBUTE_DNA.lookup.get(gene).grade,
      q: layout[index][0], r: layout[index][1], rotation: layout[index][2] }));
    const dna = pieces && validateDna({ version: 6, level, budget: 999999999, pieces }, level, 999999999);
    if (!dna) throw new Error("Invalid tribe DNA: " + key);
    designs.set(key, dna);
  }
  return cloneDna(designs.get(key));
}

export function sameTribeDesign(first, second) {
  if (!first.dna || !second.dna) return false;
  return JSON.stringify(first.dna.pieces) === JSON.stringify(second.dna.pieces);
}

export function tribeDnaTemplate(dna, role, state) {
  const previous = state.templates.find(template => sameTribeDesign(template, { dna }));
  if (previous) return { ...previous, productionRole: role };
  const slots = Object.keys(dnaAppearance(dna));
  return { id: null, name: suggestTemplateName(slots, state.templates), dna, slots,
    attributeLevels: Object.fromEntries(slots.map(key => [key, 1])), revision: 1, productionRole: role };
}
