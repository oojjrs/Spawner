#!/usr/bin/env python3
"""Publish unchanged full-body sheets and deterministic runtime registration.
Source atlases remain byte-exact. Only portraits are exact first-cell crops.
Run from any directory with Pillow installed.
"""
from pathlib import Path
import hashlib, json, math, shutil
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SPECIES = ('bean', 'spore', 'pebble', 'spring')
ACTIONS = ('idle', 'walk', 'attack', 'hurt', 'birth', 'death')
# Ground anchors from source packing records (bean/spring), or first-cell
# visible ground contact (spore/pebble). Reference lengths are alpha>=16
# neutral-body longest dimensions, not atlas/cave dimensions.
REGISTRATION = {
    'bean': (256, 448, 279),
    'spore': (256, 416, 297),
    'pebble': (256, 450, 399),
    'spring': (216, 368, 239),
}
# Full birth scenes contain their own nest and travel. Anchor the FINAL body,
# never the whole scene's bounds; otherwise the idle handoff changes size.
# Bean: source complete-scene camera.targetFloor + constantWholeCelScale.
# Other endpoints measured in the final published frame at alpha>=16.
BIRTH = {
    'bean': (430, 446, 279 * .15625),
    'spore': (534, 477, 46),
    'pebble': (397, 440, 141),
    'spring': (286, 351, 107),
}

def sha(path): return hashlib.sha256(path.read_bytes()).hexdigest()
def register(policy, path, width, height, columns, rows):
    im = Image.open(path)
    policy['images'][path.relative_to(ROOT).as_posix()] = {
        'display': [256, round(256 * height / width, 6)],
        'grid': [columns, rows],
        'nativeSource': {'sha256': sha(path), 'dimensions': list(im.size), 'frame': [width, height]},
    }

def main():
    policy_path = ROOT / 'DesignAssets/image-sizes.json'
    policy = json.loads(policy_path.read_text())
    definitions = {}
    for tribe in SPECIES:
        source = ROOT / f'AnimationCandidates/{tribe}-blade-carapace-fullbody-v1-20261107'
        manifest = json.loads((source / 'publication-manifest.json').read_text())
        output = ROOT / 'DesignAssets/Animations/BladeCarapaceV1' / tribe
        output.mkdir(parents=True, exist_ok=True)
        actions = {}
        for action in ACTIONS:
            record = manifest['actions'][action]
            src = ROOT / record['sheet'] if record['sheet'].startswith('AnimationCandidates/') else source / record['sheet']
            assert sha(src) == record['sheetSHA256'], src
            dest = output / f'{action}.png'
            shutil.copyfile(src, dest)
            size = record.get('frameSize', manifest.get('frameSize'))
            width, height = (size, size) if isinstance(size, int) else size
            columns = record.get('columns', manifest.get('columns'))
            count = record.get('frameCount', record.get('frames'))
            rows = math.ceil(count / columns)
            assert Image.open(dest).size == (width * columns, height * rows)
            px, py, length = BIRTH[tribe] if action == 'birth' else REGISTRATION[tribe]
            clip = dict(image=dest.relative_to(ROOT).as_posix(), sourceFacing='right',
                frameSize=width, frameHeight=height, columns=columns, frameCount=count,
                durationsMs=record['durationsMs'], durationMs=sum(record['durationsMs']),
                pivotX=px, pivotY=py, referenceLength=length, viewSize=length,
                registrationScale=1, loop=action in ('idle', 'walk'))
            if action == 'birth':
                clip.update(fullScene=True, worldTravelIncludedInPixels=True,
                            sceneAnchor='final-body-floor', sceneIncludesNest=True)
            actions[action] = clip
            register(policy, dest, width, height, columns, rows)
            if action == 'idle':
                portrait = output / 'portrait.png'
                Image.open(dest).crop((0, 0, width, height)).save(portrait)
                register(policy, portrait, width, height, 1, 1)
        definitions[f'{tribe}/blade-carapace'] = dict(
            portrait=portrait.relative_to(ROOT).as_posix(), reference=actions['idle'], actions=actions)
    header = '''// Generated by scripts/register-blade-carapace.py from published full-body art.
// No ranged clip or procedural body/part composition is registered.
// Full-scene birth uses the final body's floor and scale, including its nest.
'''
    text = header + 'export const BLADE_CARAPACE_ACTION_ART = Object.freeze(' + json.dumps(definitions, indent=2) + ');\n'
    text += '''\nexport const BLADE_CARAPACE_IMAGE_ASSETS = Object.freeze([
  ...new Set(Object.values(BLADE_CARAPACE_ACTION_ART).flatMap(definition => [
    definition.portrait, ...Object.values(definition.actions).map(action => action.image),
  ])),
]);
'''
    (ROOT / 'client/blade-carapace-assets.mjs').write_text(text)
    policy_path.write_text(json.dumps(policy, indent=2) + '\n')

if __name__ == '__main__': main()
