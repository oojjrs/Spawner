const agent = (id, ownerId, tribe, x) => ({ id, ownerId, tribe, x, y: 100, health: 100,
  moveStartedAt: 0, moveDuration: 0, facing: 1, attributes: {}, combatDisposition: "aggressive",
  stats: { health: 100, speed: 1, vision: 4, dna: dna() } });
function scenario(id, label) {
  const source = agent("source", "a", "bean", 100), target = agent("target", "b", "spore", 102), events = [];
  // Controlled review stats force a real server branch; these are not player builds.
  if (id === "critical") source.stats.dna.critical = 100;
  if (id === "dodge") target.stats.dna.evasion = 100;
  if (id === "parry") target.stats.dna.parry = 100;
  if (id === "block") target.stats.dna.block = 100;
  const game = agents => ({ agents, receiveDamage(agent, amount) { agent.health = Math.max(0, agent.health - amount); } });
  const environment = { world: { terrain: new Uint8Array(320 * 320) }, games: new Map([
    ["a", game([source])], ["b", game([target])]
  ]), combatRandom: () => .99, damageRandom: () => .5, onCombatEvent: event => events.push(event) };
  const combat = createCombat(environment);
  combat.update(source, 0);
  const sourceStart = structuredClone(source), targetStart = structuredClone(target);
  combat.update(source, .3);
  if (id === "projectile-cancel") environment.games.get("b").agents.length = 0;
  for (const time of [.45, .3 + 2 / 6, 1.4]) combat.update(source, time);
  const streamId = events[0].streamId;
  return { id, label, origin: "actual server/combat.mjs controlled one-shot fixture", seconds: 1.4,
    background: "DesignAssets/Combat/grassland.webp", source: sourceStart, target: targetStart,
    sourceForm: UNIT_RANGED_FORMS.bean, targetForm: UNIT_RANGED_FORMS.spore,
    events: JSON.parse(JSON.stringify(events).replaceAll(streamId, "review-server-" + id)) };
}
