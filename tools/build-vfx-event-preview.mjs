const completed = new Set(), chunks = ["const modules = Object.create(null);"];
function bundle(name) {
  if (completed.has(name)) return;
  const path = resolve(root, name), source = readFileSync(path, "utf8");
  const imports = [...source.matchAll(/^import\s+\{([^}]+)\}\s+from\s+["']([^"']+)["'];?\r?$/gm)];
  let transformed = source;
  for (const item of imports) {
    const dependency = relative(root, resolve(dirname(path), item[2])).replaceAll("\\", "/");
    bundle(dependency);
    transformed = transformed.replace(item[0], "const {" + item[1] + "} = modules[" + JSON.stringify(dependency) + "];");
  }
  const names = [...source.matchAll(/^export\s+(?:function|const|let|class)\s+([\w$]+)/gm)].map(match => match[1]);
  transformed = transformed.replace(/^export\s+/gm, "");
  if (/^(?:import|export)\s/m.test(transformed)) throw new Error("Unsupported review module: " + name);
  chunks.push("modules[" + JSON.stringify(name) + "] = (() => {\n" + transformed + "\nreturn {" + names.join(",") + "};\n})();");
  completed.add(name);
}
bundle("client/vfx-event-preview.mjs");
writeFileSync(resolve(root, "client/vfx-event-preview.js"), "// Generated by tools/build-vfx-event-preview.mjs\n(() => {\n" + chunks.join("\n") + "\n})();\n");
